import { expect, test } from '@playwright/test';

test('the console receives verified content and packet traces from the real pipeline', async ({ page }) => {
  test.skip(!process.env.TEAMWATER_PIPELINE_URL, 'Start the pipeline and point the Vite proxy at it first.');
  test.setTimeout(60_000);
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto('/');
  await expect(page.getByText('6 / 6 nodes online')).toBeVisible();
  await expect(page.getByText('Simulated Mesh Network', { exact: true })).toBeVisible();
  const boss = page.getByTestId('phone-boss');
  const employee = page.getByTestId('phone-employee');
  const text = `Browser check ${Date.now()}: Please fix the code. The recovered content must include this ending beyond the sixty-character preview.`;
  await boss.getByLabel('Message input').fill(text);
  await boss.getByRole('button', { name: 'Send message', exact: true }).click();
  await expect(page.getByTestId('trace-packet')).toBeVisible();
  const firstEvent = await page.getByTestId('trace-packet').getAttribute('data-event-id');
  await expect.poll(() => page.getByTestId('trace-packet').getAttribute('data-event-id')).not.toBe(firstEvent);
  await expect(employee.getByText(text, { exact: true })).toBeVisible({ timeout: 45_000 });
  await expect(page.getByTestId('packet-log')).toContainText('Verified receipt', { timeout: 15_000 });
  await expect(page.getByRole('columnheader', { name: 'Sim time' })).toBeVisible();
  await expect(page.getByRole('group', { name: 'Range', exact: true })).toContainText('180');
  await expect(page.getByRole('group', { name: 'Delay', exact: true })).not.toContainText('Unavailable');
  await expect(page.getByRole('group', { name: 'Packet loss', exact: true })).not.toContainText('Unavailable');
  await page.getByRole('button', { name: 'Replay selected trace' }).click();
  const packet = page.getByTestId('trace-packet');
  const start = await packet.evaluate(node => { const matrix = (node as SVGGraphicsElement).getCTM()!; return { x: matrix.e, y: matrix.f }; });
  await expect.poll(() => packet.evaluate((node, previous) => { const matrix = (node as SVGGraphicsElement).getCTM()!; return Math.hypot(matrix.e - previous.x, matrix.f - previous.y); }, start)).toBeGreaterThan(5);
  expect(errors).toEqual([]);
});
